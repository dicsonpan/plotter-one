/**
 * 文字转路径。
 *
 * 刻字机不需要"填充"，只需要"笔画中心线"。所以文字最终要么是：
 *   - 单线字体：每个字直接是若干条折线，单线刀一次过
 *   - 普通字体的轮廓：用 Canvas 取字形轮廓（前端做），再输出外轮廓
 *
 * 服务端这套实现走「内置笔画字体」路线：把常用字符定义成单线笔画坐标，
 * 好处是完全可控、无字体依赖、输出体积小、任意机器都能刻准。
 *
 * 中文字符笔画多，完整内置不现实（几千字），所以策略是：
 *   - 数字 / 大写字母 / 小写字母 / 常用符号：内置单线笔画，精细可控
 *   - 中文及其他字符：交给前端用 Canvas 文字轮廓转换（浏览器有完整字体）
 *
 * 这样"12345 · ABC · SK-2026"这类标牌内容（刻字机最常见的场景）
 * 服务端直接搞定，中文长句由前端轮廓方案兜底。
 */

