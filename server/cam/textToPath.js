/**
 * 字体度量。字形实际绘制在 y ∈ [Y_MIN, Y_MAX]、x ∈ [X_MIN, X_MAX]，
 * 而不是整个 0..GLYPH_W × 0..GLYPH_H。
 * 所有内置字形底部在 y=2、顶部在 y=8，左右各留 1 单位边距，
 * 所以字高 6、字宽 4。sizeMm 指的是「大写字高」，必须按实际字形高度换算，
 * 否则做出来小了 40%；同理字距也要按实际字宽算，否则一个字能占掉 80mm。
 */
const X_MIN = 1, X_MAX = 5;
const Y_MIN = 2, Y_MAX = 8;
const GLYPH_W = X_MAX - X_MIN;          // 实际字宽 = 4
const GLYPH_H = Y_MAX - Y_MIN;          // 实际字高 = 6
const GLYPH_GAP = 1.2;                  // 字间距（字体单位）
const BASE_ADVANCE = GLYPH_W + GLYPH_GAP; // 步进 = 5.2 个单位

/**
 * 生成文字路径（单线笔画）
 * @param {object} o
 * @param {string} o.text
 * @param {number} o.sizeMm 大写字高（mm），从基线量到字顶
 * @param {number} o.letterSpacing 字距倍数（0=标准）
 * @param {number} o.x 起始 X
 * @param {number} o.y 基线 Y
 */
export function textToPath(o) {
  const text = String(o.text || '');
  const sizeMm = o.sizeMm || 20;
  const gapMul = 1 + (o.letterSpacing || 0);
  const scale = sizeMm / GLYPH_H;             // 6 个字体单位 → sizeMm
  const advance = BASE_ADVANCE * scale * gapMul;
  const rotation = ((o.rotation || 0) * Math.PI) / 180;
  const cosR = Math.cos(rotation), sinR = Math.sin(rotation);
  const baseX = o.x || 0;
  const baseY = o.y || 0;

  const pts = [];
  let cursor = 0;
  const unsupported = [];

  for (const ch of text.toUpperCase()) {
    const strokes = STROKE_FONT[ch];
    if (strokes === undefined) {
      unsupported.push(ch);
      // 未知字符：画一个方框占位，视觉上能看出缺字
      const box = [[[1,2],[5,2],[5,8],[1,8],[1,2]]];
      for (const s of box) pts.push(s.map(([px, py]) => transform(px, py, cursor)));
      cursor += advance;
      continue;
    }
    for (const s of strokes) {
      pts.push(s.map(([px, py]) => transform(px, py, cursor)));
    }
    cursor += advance;
  }

  function transform(px, py, cx) {
    // 减去 X_MIN/Y_MIN 让字形左上角对齐到游标，而不是被边距推出去
    const x = cx + (px - X_MIN) * scale;
    const y = (py - Y_MIN) * scale;
    return {
      x: baseX + x * cosR - y * sinR,
      y: baseY + x * sinR + y * cosR,
    };
  }

  const path = makePath();
  for (const stroke of pts) {
    if (stroke.length < 2) continue;
    const sub = makeSubpath(stroke[0].x, stroke[0].y);
    for (let i = 1; i < stroke.length; i++) addLine(sub, stroke[i].x, stroke[i].y);
    path.subpaths.push(sub);
  }

  return {
    ...path,
    meta: {
      unsupported,
      advanceWidth: cursor,
      sizeMm,
      // 双语：note 保持中文以兼容既有调用方，noteEn 供英文界面使用
      note: unsupported.length
        ? `字符 ${unsupported.join('')} 超出内置单线字体，已用方框占位。中文请用前端轮廓模式。`
        : '内置单线字体输出',
      noteEn: unsupported.length
        ? `Characters ${unsupported.join('')} are outside the built-in stroke font and were replaced with boxes. For Chinese use the outline mode.`
        : 'Built-in stroke font output',
    },
  };
}

/** 服务端是否支持该字符的内置单线笔画 */
export function hasStrokeGlyph(ch) {
  return Object.prototype.hasOwnProperty.call(STROKE_FONT, ch.toUpperCase());
}

